import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const original = await readFile(new URL("../extension/stacker.js", import.meta.url), "utf8");
let source = original.replace("export function createStacker", "export function createQueryStacker")
  .replace("{ batchSize = 32, onError = console.error, onGroupCreated, validateGroupIds }", "{ batchSize = 32, queryThreshold = 2, onError = console.error, onGroupCreated, validateGroupIds }");
if (!source.includes("queryThreshold = 2")) throw new Error("Options anchor changed; review generator");
const begin = source.indexOf("  /** @param {number} id @returns {Promise<Tab | undefined>} */");
const end = source.indexOf("  /** @param {Tab | undefined} source", begin);
if (begin < 0 || end < 0) throw new Error("Read strategy anchor changed; review generator");
source = source.slice(0, begin) + `  const reads = new Map();
  function read(id, windowId) {
    const { promise, resolve, reject } = Promise.withResolvers();
    let pending = reads.get(windowId);
    if (!pending) {
      pending = [];
      reads.set(windowId, pending);
      queueMicrotask(async () => {
        reads.delete(windowId);
        try {
          if (pending.length < queryThreshold) {
            await Promise.all(pending.map(async request => {
              try { request.resolve(await api.tabs.get(request.id)); }
              catch (error) { if (missingTab(error)) request.resolve(undefined); else request.reject(error); }
            }));
          } else {
            const tabs = await api.tabs.query({ windowId });
            const requested = new Set(pending.map(request => request.id));
            const found = new Map(tabs.filter(tab => requested.has(tab.id)).map(tab => [tab.id, tab]));
            for (const request of pending) request.resolve(found.get(request.id));
          }
        } catch (error) {
          for (const request of pending) {
            if (/^Invalid window ID:/.test(message(error))) request.resolve(undefined);
            else request.reject(error);
          }
        }
      });
    }
    pending.push({ id, resolve, reject });
    return promise;
  }

` + source.slice(end);
source = source.replace("chunk.map(read)", "chunk.map(id => read(id, root.windowId))")
  .replace("[read(source.id), read(anchor.id)]", "[read(source.id, source.windowId), read(anchor.id, source.windowId)]")
  .replace("[read(source.id), read(id)]", "[read(source.id, source.windowId), read(id, source.windowId)]")
  .replace("read(batch[0].sourceTabId)", "read(batch[0].sourceTabId, windowId)")
  .replace("read(first.sourceTabId), ...jobs.map(job => read(job.tabId))", "read(first.sourceTabId, first.windowId), ...jobs.map(job => read(job.tabId, job.windowId))");
await writeFile(new URL("query-stacker.js", import.meta.url),
  `// Experimental fresh-window-query challenger; generated by make-query.js.\n// Production kernel SHA-256: ${createHash("sha256").update(original).digest("hex")}\n` + source);
